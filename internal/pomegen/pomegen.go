// Package pomegen generates the Emela of a provider's Pome from its manifest (ADR 0009): for each
// kind with a spec, a record type and a function that declares a resource of it; for each string
// with values an enum; for each object a type. A reference to another kind is a field of that
// kind's type: the generated function names the referenced resource in the spec and adds it to
// after, so that a declaration cannot refer to something it never declared.
//
// The output is deterministic: the same manifest gives the same bytes.
package pomegen

import (
	"errors"
	"fmt"
	"slices"
	"strings"
	"unicode"

	"github.com/ieyoukan/mamela/provider/protocol"
)

// GeneratedMark is in every generated Pome module.
const GeneratedMark = "Code generated by `mamela provider pome` from the provider's manifest; DO NOT EDIT."

// Options name what the manifest does not.
type Options struct {
	// Module is the Pome's module ("Kv"), for its documentation.
	Module string
}

// Generate returns the Emela source (src/lib.emel) of a provider's Pome.
func Generate(m protocol.Manifest, o Options) ([]byte, error) {
	g := &gen{m: m, kinds: map[protocol.ResourceKind]*kindInfo{}, objects: map[string]protocol.Field{}, enums: map[string][]string{}}
	return g.run(o)
}

// Names are the Emela type and function a kind's Pome gets ("KVItem": KvItem, kv_item).
func Names(kind protocol.ResourceKind) (typeName, fnName string) {
	return upper(string(kind)), snake(string(kind))
}

type kindInfo struct {
	kind     protocol.Kind
	typeName string // KvItem
	fnName   string // kv_item
}

type gen struct {
	m       protocol.Manifest
	kinds   map[protocol.ResourceKind]*kindInfo
	order   []protocol.ResourceKind
	objects map[string]protocol.Field // by Emela type name
	objOrd  []string
	enums   map[string][]string // by Emela type name: the values
	enumOrd []string
	b       strings.Builder
	numbers bool
}

func (g *gen) run(o Options) ([]byte, error) {
	if err := g.m.Check(); err != nil {
		return nil, err
	}
	names := map[string]string{}
	for _, k := range g.m.Kinds {
		if len(k.Spec) == 0 {
			continue
		}
		ki := &kindInfo{kind: k, typeName: upper(string(k.Kind)), fnName: snake(string(k.Kind))}
		if !validUpper(ki.typeName) || !validLower(ki.fnName) {
			return nil, fmt.Errorf("kind %s: no Emela name can be made of it", k.Kind)
		}
		if prev, dup := names[ki.typeName]; dup {
			return nil, fmt.Errorf("kinds %s and %s make the same Emela type %s", prev, k.Kind, ki.typeName)
		}
		names[ki.typeName] = string(k.Kind)
		g.kinds[k.Kind] = ki
		g.order = append(g.order, k.Kind)
	}
	if len(g.order) == 0 {
		return nil, errors.New("no kind of the provider gives its spec: nothing to generate (provider/kit gives it from Spec())")
	}
	// Types first: what each kind's fields need (objects, enums), checked for clashes.
	for _, k := range g.order {
		ki := g.kinds[k]
		if err := g.collect(ki.typeName, ki.kind.Spec, names); err != nil {
			return nil, fmt.Errorf("kind %s: %w", k, err)
		}
	}
	g.header(o)
	for _, k := range g.order {
		if err := g.kindDecl(g.kinds[k]); err != nil {
			return nil, err
		}
	}
	for _, name := range g.enumOrd {
		g.enumDecl(name)
	}
	for _, name := range g.objOrd {
		if err := g.objectDecl(name); err != nil {
			return nil, err
		}
	}
	g.helpers()
	return []byte(g.b.String()), nil
}

// collect finds the enums and objects of fields, named by the type they belong to.
func (g *gen) collect(owner string, fields []protocol.Field, names map[string]string) error {
	seen := map[string]string{}
	for _, f := range fields {
		ef := emelaField(f.Name)
		if !validLower(ef) {
			return fmt.Errorf("field %s: no Emela name can be made of it", f.Name)
		}
		if prev, dup := seen[ef]; dup || ef == "name" {
			return fmt.Errorf("fields %s and %s make the same Emela field %s", prev, f.Name, ef)
		}
		seen[ef] = f.Name
		if err := g.collectType(owner, f, names); err != nil {
			return fmt.Errorf("field %s: %w", f.Name, err)
		}
	}
	return nil
}

func (g *gen) collectType(owner string, f protocol.Field, names map[string]string) error {
	switch f.Type {
	case protocol.FieldString:
		if len(f.Values) > 0 {
			name := owner + upper(f.Name)
			if _, err := variants(f.Values); err != nil {
				return err
			}
			if prev, ok := g.enums[name]; ok {
				if !slices.Equal(prev, f.Values) {
					return fmt.Errorf("enum %s is made twice with other values", name)
				}
				return nil
			}
			if _, clash := names[name]; clash {
				return fmt.Errorf("enum %s clashes with another type", name)
			}
			names[name] = "enum"
			g.enums[name] = f.Values
			g.enumOrd = append(g.enumOrd, name)
		}
	case protocol.FieldInt:
		g.numbers = true
	case protocol.FieldRef:
		if _, ok := g.kinds[f.Ref]; !ok {
			return fmt.Errorf("refers to kind %s, which is not a kind of the provider with a spec", f.Ref)
		}
	case protocol.FieldList:
		e := *f.Elem
		e.Name = f.Name
		return g.collectType(owner, e, names)
	case protocol.FieldObject:
		name := upper(f.TypeName)
		if !validUpper(name) {
			return fmt.Errorf("object type %q: no Emela name can be made of it", f.TypeName)
		}
		if prev, ok := g.objects[name]; ok {
			if !sameFields(prev.Fields, f.Fields) {
				return fmt.Errorf("object type %s is used with other fields", name)
			}
			return nil
		}
		if _, clash := names[name]; clash {
			return fmt.Errorf("object type %s clashes with another type", name)
		}
		names[name] = "object"
		g.objects[name] = f
		g.objOrd = append(g.objOrd, name)
		return g.collect(name, f.Fields, names)
	}
	return nil
}

func sameFields(a, b []protocol.Field) bool {
	return slices.EqualFunc(a, b, func(x, y protocol.Field) bool {
		return x.Name == y.Name && x.Type == y.Type && x.Optional == y.Optional && x.Ref == y.Ref &&
			x.TypeName == y.TypeName && slices.Equal(x.Values, y.Values) &&
			(x.Elem == nil) == (y.Elem == nil) && (x.Elem == nil || sameFields([]protocol.Field{*x.Elem}, []protocol.Field{*y.Elem})) &&
			sameFields(x.Fields, y.Fields)
	})
}

// item writes one element of a list literal, each of its lines indented.
func (g *gen) item(indent, s string) {
	lines := strings.Split(s, "\n")
	for i, l := range lines {
		g.p("%s%s", indent, l)
		if i == len(lines)-1 {
			g.p(",")
		}
		g.p("\n")
	}
}

func (g *gen) p(format string, args ...any) { fmt.Fprintf(&g.b, format, args...) }

func (g *gen) header(o Options) {
	module := o.Module
	if module == "" {
		module = "This Pome"
	}
	g.p("## %s: the resources of the Mamela provider %q, version %s.\n", module, g.m.Provider, g.m.Version)
	g.p("##\n")
	g.p("## %s\n", GeneratedMark)
	g.p("## Importing this Pome is how a declaration uses the provider: the functions here declare its\n")
	g.p("## resources, and the Pome holds the provider's program (mamela-provider.toml), which Mamela runs\n")
	g.p("## isolated. A field that refers to another resource takes its value, so that the reference names\n")
	g.p("## something declared; Mamela plans a resource once those it refers to exist.\n\n")
	g.p("import Mamela\nimport Mamela.{Ref}\nimport Dynamic.{Dynamic, Text, Items}\n")
	if g.numbers {
		g.p("import Dynamic.Number\n")
	}
	g.p("\n## The provider, as its manifest names it.\npub const PROVIDER = %q\n", g.m.Provider)
}

func (g *gen) doc(indent, text string) {
	for _, line := range strings.Split(strings.TrimSpace(text), "\n") {
		g.p("%s## %s\n", indent, strings.TrimSpace(line))
	}
}

// fieldType is the Emela type of a field (owner names its enums).
func (g *gen) fieldType(owner string, f protocol.Field) string {
	t := g.baseType(owner, f)
	if f.Optional && f.Type != protocol.FieldList {
		return "Option[" + t + "]"
	}
	return t
}

func (g *gen) baseType(owner string, f protocol.Field) string {
	switch f.Type {
	case protocol.FieldString:
		if len(f.Values) > 0 {
			return owner + upper(f.Name)
		}
		return "String"
	case protocol.FieldInt:
		return "Int"
	case protocol.FieldBool:
		return "Bool"
	case protocol.FieldRef:
		return g.kinds[f.Ref].typeName
	case protocol.FieldList:
		e := *f.Elem
		e.Name, e.Optional = f.Name, false
		return "List[" + g.baseType(owner, e) + "]"
	case protocol.FieldObject:
		return upper(f.TypeName)
	}
	return "Never"
}

func (g *gen) record(name string, fields []protocol.Field, withName bool) {
	var parts []string
	if withName {
		parts = append(parts, "name: String")
	}
	for _, f := range fields {
		parts = append(parts, emelaField(f.Name)+": "+g.fieldType(name, f))
	}
	g.p("pub type %s(\n", name)
	for _, p := range parts {
		g.p("  %s,\n", p)
	}
	g.p(")\n")
}

func (g *gen) fieldDocs(fields []protocol.Field) {
	var docs []string
	for _, f := range fields {
		d := f.Doc
		if len(f.Values) > 0 {
			d = strings.TrimSpace(d + " (" + strings.Join(f.Values, ", ") + ")")
		}
		if f.Optional {
			d = strings.TrimSpace(d + " (optional)")
		}
		if d != "" {
			docs = append(docs, fmt.Sprintf("`%s`: %s", emelaField(f.Name), d))
		}
	}
	if len(docs) > 0 {
		g.p("##\n")
		for _, d := range docs {
			g.doc("", d)
		}
	}
}

func (g *gen) kindDecl(ki *kindInfo) error {
	k := ki.kind
	g.p("\n")
	doc := k.Doc
	if doc == "" {
		doc = fmt.Sprintf("A %s of the provider %s.", k.Kind, g.m.Provider)
	}
	g.doc("", doc)
	g.fieldDocs(k.Spec)
	g.record(ki.typeName, k.Spec, true)
	g.p("\n## Declares the %s: Mamela makes it so, through the provider.\n", k.Kind)
	g.p("pub fn %s(graph: Mamela.Graph, r: %s) -> Mamela.Graph {\n", ki.fnName, ki.typeName)
	g.p("  spec = List.flatten(\n    [\n")
	for _, f := range k.Spec {
		g.item("      ", g.specEntry(ki.typeName, f, "r."+emelaField(f.Name)))
	}
	g.p("    ],\n  )\n")
	after := g.afterParts(ki.typeName, k.Spec, "r")
	if len(after) == 0 {
		g.p("  Mamela.provided(graph, PROVIDER, %q, r.name, spec)\n}\n", k.Kind)
	} else {
		g.p("  after = List.flatten(\n    [\n")
		for _, a := range after {
			g.item("      ", a)
		}
		g.p("    ],\n  )\n")
		g.p("  Mamela.provided_after(graph, PROVIDER, %q, r.name, spec, after)\n}\n", k.Kind)
	}
	g.p("\n## A reference to the %s, for what needs it first.\n", k.Kind)
	g.p("pub fn %s_ref(r: %s) -> Ref {\n  Ref(kind: %q, name: r.name)\n}\n", ki.fnName, ki.typeName, k.Kind)
	if k.Node {
		g.p("\n## The %s as a node: what mamelet runs on, to declare packages and services on.\n", k.Kind)
		g.p("pub fn %s_node(r: %s) -> Mamela.Node {\n  Mamela.Node(name: r.name)\n}\n", ki.fnName, ki.typeName)
	}
	return nil
}

// specEntry is a list of the spec's entries for a field: one, or none for an absent optional.
func (g *gen) specEntry(owner string, f protocol.Field, expr string) string {
	key := fmt.Sprintf("%q", f.Name)
	switch {
	case f.Optional && f.Type == protocol.FieldList:
		return fmt.Sprintf("if List.is_empty(%s) { [] } else { [(%s, %s)] }", expr, key, g.toDynamic(owner, f, expr))
	case f.Optional:
		inner := f
		inner.Optional = false
		return fmt.Sprintf("%s match {\n  Some(v) -> [(%s, %s)]\n  None -> []\n}", expr, key, g.toDynamic(owner, inner, "v"))
	}
	return fmt.Sprintf("[(%s, %s)]", key, g.toDynamic(owner, f, expr))
}

// toDynamic converts a (present) value of a field to its spec value.
func (g *gen) toDynamic(owner string, f protocol.Field, expr string) string {
	switch f.Type {
	case protocol.FieldString:
		if len(f.Values) > 0 {
			return fmt.Sprintf("%s_text(%s)", snake(owner+upper(f.Name)), expr)
		}
		return "Text(" + expr + ")"
	case protocol.FieldInt:
		return "integer(" + expr + ")"
	case protocol.FieldBool:
		return "Dynamic.Bool(" + expr + ")"
	case protocol.FieldRef:
		return "Text(" + expr + ".name)"
	case protocol.FieldList:
		e := *f.Elem
		e.Name, e.Optional = f.Name, false
		return fmt.Sprintf("Items(%s.map(|x| %s))", expr, g.toDynamic(owner, e, "x"))
	case protocol.FieldObject:
		return fmt.Sprintf("%s_spec(%s)", snake(upper(f.TypeName)), expr)
	}
	return `Text("")` // unreachable: the manifest is checked
}

// afterParts are lists of the references of fields (of a value expr of type owner).
func (g *gen) afterParts(owner string, fields []protocol.Field, expr string) []string {
	var out []string
	for _, f := range fields {
		if !g.refers(f) {
			continue
		}
		v := expr + "." + emelaField(f.Name)
		if f.Optional && f.Type != protocol.FieldList {
			inner := f
			inner.Optional = false
			out = append(out, fmt.Sprintf("%s match {\n  Some(v) -> %s\n  None -> []\n}", v, g.refsOf(owner, inner, "v")))
			continue
		}
		out = append(out, g.refsOf(owner, f, v))
	}
	return out
}

// refsOf is a list of the references a present value of a field makes.
func (g *gen) refsOf(owner string, f protocol.Field, expr string) string {
	switch f.Type {
	case protocol.FieldRef:
		return fmt.Sprintf("[%s_ref(%s)]", g.kinds[f.Ref].fnName, expr)
	case protocol.FieldList:
		e := *f.Elem
		e.Name, e.Optional = f.Name, false
		return fmt.Sprintf("List.flatten(%s.map(|x| %s))", expr, g.refsOf(owner, e, "x"))
	case protocol.FieldObject:
		return fmt.Sprintf("%s_after(%s)", snake(upper(f.TypeName)), expr)
	}
	return "[]"
}

func (g *gen) refers(f protocol.Field) bool {
	switch f.Type {
	case protocol.FieldRef:
		return true
	case protocol.FieldList:
		return g.refers(*f.Elem)
	case protocol.FieldObject:
		return slices.ContainsFunc(f.Fields, g.refers)
	}
	return false
}

func (g *gen) enumDecl(name string) {
	vs, _ := variants(g.enums[name])
	g.p("\n## The values of %s.\npub enum %s {\n", name, name)
	for _, v := range vs {
		g.p("  %s\n", v)
	}
	g.p("}\n\nfn %s_text(v: %s) -> Dynamic {\n  v match {\n", snake(name), name)
	for i, v := range vs {
		g.p("    %s -> Text(%q)\n", v, g.enums[name][i])
	}
	g.p("  }\n}\n")
}

func (g *gen) objectDecl(name string) error {
	f := g.objects[name]
	g.p("\n")
	g.doc("", fmt.Sprintf("A %s, part of a spec.", name))
	g.fieldDocs(f.Fields)
	g.record(name, f.Fields, false)
	g.p("\nfn %s_spec(o: %s) -> Dynamic {\n  Dynamic.object(\n    List.flatten(\n      [\n", snake(name), name)
	for _, x := range f.Fields {
		g.item("        ", g.specEntry(name, x, "o."+emelaField(x.Name)))
	}
	g.p("      ],\n    ),\n  )\n}\n")
	if g.refers(f) {
		g.p("\nfn %s_after(o: %s) -> List[Ref] {\n  List.flatten(\n    [\n", snake(name), name)
		for _, a := range g.afterParts(name, f.Fields, "o") {
			g.item("      ", a)
		}
		g.p("    ],\n  )\n}\n")
	}
	return nil
}

func (g *gen) helpers() {
	if g.numbers {
		g.p("\nfn integer(n: Int) -> Dynamic {\n  Dynamic.Number(Number.from_int(n))\n}\n")
	}
}

// variants are the enum variants of string values ("ecs-tasks" -> EcsTasks).
func variants(values []string) ([]string, error) {
	seen := map[string]string{}
	var out []string
	for _, v := range values {
		n := upper(v)
		if !validUpper(n) || n == "Some" || n == "None" || n == "True" || n == "False" {
			return nil, fmt.Errorf("value %q: no Emela variant can be made of it", v)
		}
		if prev, dup := seen[n]; dup {
			return nil, fmt.Errorf("values %q and %q make the same variant %s", prev, v, n)
		}
		seen[n] = v
		out = append(out, n)
	}
	return out, nil
}

// words splits a name into words: at -, _, ., spaces, and where a lower letter or digit meets an
// upper one ("KVItem" -> KV, Item; "retentionDays" -> retention, Days).
func words(s string) []string {
	var out []string
	var cur []rune
	rs := []rune(s)
	flush := func() {
		if len(cur) > 0 {
			out = append(out, string(cur))
			cur = nil
		}
	}
	for i, r := range rs {
		switch {
		case r == '-' || r == '_' || r == '.' || r == ' ' || r == '/':
			flush()
			continue
		case unicode.IsUpper(r) && i > 0 && (unicode.IsLower(rs[i-1]) || unicode.IsDigit(rs[i-1])):
			flush()
		case unicode.IsUpper(r) && i > 0 && unicode.IsUpper(rs[i-1]) && i+1 < len(rs) && unicode.IsLower(rs[i+1]):
			flush()
		}
		cur = append(cur, r)
	}
	flush()
	return out
}

// upper is a name in UpperCamelCase ("KVItem" -> KvItem, "ecs-tasks" -> EcsTasks).
func upper(s string) string {
	var b strings.Builder
	for _, w := range words(s) {
		rs := []rune(strings.ToLower(w))
		rs[0] = unicode.ToUpper(rs[0])
		b.WriteString(string(rs))
	}
	return b.String()
}

// snake is a name in snake_case ("KVItem" -> kv_item).
func snake(s string) string {
	ws := words(s)
	for i := range ws {
		ws[i] = strings.ToLower(ws[i])
	}
	return strings.Join(ws, "_")
}

var reserved = map[string]bool{}

func init() {
	for _, w := range strings.Fields(`fn type enum error const trait impl effect handler layer import pub opaque suspend
		if else match fail escape use with assert self as var return while loop let mut in where do try catch throw
		async yield defer macro mod graph spec after r o v x`) {
		reserved[w] = true
	}
}

// emelaField is the Emela name of a spec field ("retentionDays" -> retention_days; a reserved word
// gets a trailing _).
func emelaField(name string) string {
	s := snake(name)
	if reserved[s] {
		s += "_"
	}
	return s
}

func validUpper(s string) bool {
	for i, r := range s {
		if !(r < unicode.MaxASCII && (unicode.IsLetter(r) || (i > 0 && unicode.IsDigit(r)))) || (i == 0 && !unicode.IsUpper(r)) {
			return false
		}
	}
	return s != ""
}

func validLower(s string) bool {
	for i, r := range s {
		if !(r < unicode.MaxASCII && (unicode.IsLower(r) || r == '_' || (i > 0 && unicode.IsDigit(r)))) {
			return false
		}
	}
	return s != ""
}
