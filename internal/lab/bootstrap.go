// Grant is one ACL entry the operating token receives: a role with exact privileges on one path.
// Each path gets its own role, so a privilege never leaks to a path where it is not needed.
type Grant struct {
	Path    string
	Role    string
	Privs   []string
	Reasons map[string][]string // privilege -> the API calls that need it
}

// Grants returns the complete set of permissions of the operating token, derived from the
// permission catalog (internal/proxmox/permissions.go) and the parameters the provider sends for
// this site. Preflight refuses to run if the token has less or more than this. The lab pool's
// grant comes first.
func (s *Site) Grants() []Grant {
	pool := "/pool/" + s.Boundary.Pool
	paths := s.scopePaths()
	byPath := map[string]*Grant{}
	var order []string
	for _, r := range proxmox.NeedsFor(s.AllCalls()) {
		pr := paths[r.Scope]
		g := byPath[pr[0]]
		if g == nil {
			g = &Grant{Path: pr[0], Role: pr[1], Reasons: map[string][]string{}}
			byPath[pr[0]] = g
			order = append(order, pr[0])
		}
		if !slices.Contains(g.Privs, r.Priv) {
			g.Privs = append(g.Privs, r.Priv)
		}
		g.Reasons[r.Priv] = append(g.Reasons[r.Priv], r.Reasons...)
	}
	slices.SortStableFunc(order, func(a, b string) int {
		switch {
		case a == pool:
			return -1
		case b == pool:
			return 1
		}
		return strings.Compare(a, b)
	})
	out := make([]Grant, 0, len(order))
	for _, p := range order {
		g := *byPath[p]
		slices.Sort(g.Privs)
		out = append(out, g)
	}
	return out
}

// ToolCalls are the operating token's calls outside operations: preflight and `mamela lab tunnel`.
var ToolCalls = []proxmox.Call{
	{Method: "GET", Path: "/access/permissions", When: "preflight"},
	{Method: "GET", Path: "/cluster/resources", When: "preflight: what the token can see"},
	{Method: "GET", Path: "/nodes/{node}/storage", When: "preflight: the image storage accepts imports"},
	{Method: "GET", Path: "/nodes/{node}/qemu/{vmid}/agent/network-get-interfaces", When: "mamela lab tunnel: the VM's address"},
}

// AllCalls is every call the operating token may make for this site: observing, each operation
// the provider carries out, and the tools. The grants are exactly what these need.
func (s *Site) AllCalls() []proxmox.Call {
	calls := append(append(append(slices.Clone(pve.ObserveCalls), ToolCalls...), pve.DestroyCalls...), pve.RebootCalls...)
	for _, op := range []policy.Op{policy.OpCreateVM, policy.OpStartVM, policy.OpGrowVMDisk, policy.OpResizeVMCPU, policy.OpResizeVMMemory} {
		c, _ := pve.OperationCalls(op, s.ControlPlane.Enabled())
		calls = append(calls, c...)
	}
	return calls
}

// scopePaths maps the catalog's scopes to the site's ACL paths and the role used there.
func (s *Site) scopePaths() map[proxmox.Scope][2]string {
	pool := "/pool/" + s.Boundary.Pool
	return map[proxmox.Scope][2]string{
		proxmox.ScopeVM:           {pool, "MamelaLabVM"}, // the pool's ACL reaches its VMs
		proxmox.ScopePool:         {pool, "MamelaLabVM"},
		proxmox.ScopeDiskStorage:  {"/storage/" + s.Placement.DiskStorage, "MamelaLabDisk"},
		proxmox.ScopeImageStorage: {"/storage/" + s.Placement.ImageStorage, "MamelaLabImage"},
		proxmox.ScopeBridge:       {"/sdn/zones/" + s.Placement.SDNZone + "/" + s.Placement.Bridge, "MamelaLabNet"},
		proxmox.ScopeNode:         {"/nodes/" + s.Proxmox.Node, "MamelaLabNode"},
		proxmox.ScopeRoot:         {"/", "MamelaLabRoot"},
	}
}

// BootstrapScript is the setup a person reviews and runs as root on a cluster node. It is
// idempotent: running it again converges to the same state. The only thing it removes is ACL
// entries of Mamela's own operating user and token that the permission catalog no longer needs.
func (s *Site) BootstrapScript() string {
	user := s.TokenUser()
	_, labToken, _ := strings.Cut(s.Proxmox.TokenID, "!")
	auditUser, auditToken, _ := strings.Cut(s.Proxmox.AuditTokenID, "!")
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }

	w("#!/usr/bin/env bash")
	w("# Mamela lab bootstrap — generated by `mamela lab bootstrap`. Review every line before running.")
	w("# Run as root on one node of the cluster. It adds a pool, roles, users, tokens and ACLs, and removes")
	w("# ACL entries of %s and %s that Mamela no longer needs. It touches no guest,", user, s.Proxmox.TokenID)
	w("# no other user's permissions, and no storage, network or HA setting except the step 2 below.")
	w("set -euo pipefail")
	w("")
	w("exists() { pvesh get \"$1\" --output-format json >/dev/null 2>&1; }")
	w("ensure_role() { if exists \"/access/roles/$1\"; then pveum role modify \"$1\" --privs \"$2\"; else pveum role add \"$1\" --privs \"$2\"; fi; }")
	w("ensure_user() { exists \"/access/users/$1\" || pveum user add \"$1\" --comment \"$2\"; }")
	w("new_token() { # prints the secret once; store it in the given file with mode 600")
	w("  if exists \"/access/users/$1/token/$2\"; then echo \"token $1!$2 already exists (secret not shown again)\"; return; fi")
	w("  echo \"== token $1!$2 — save the 'value' below into $3 (chmod 600) on the machine that runs Mamela\"")
	w("  pveum user token add \"$1\" \"$2\" --privsep 1 --comment \"$4\"")
	w("}")
	w("")
	w("# 1. The lab pool. Mamela creates guests only inside it.")
	w("exists \"/pools/%s\" || pveum pool add %s --comment \"Mamela lab: guests here are managed by Mamela\"", s.Boundary.Pool, s.Boundary.Pool)
	w("")
	w("# 2. Let the image storage hold importable disk images (content type \"import\"). This only adds")
	w("#    \"import\" to the storage's content types; the existing ones are kept.")
	w("content=\"$(pvesh get /storage/%s --output-format json | python3 -c 'import json,sys; print(json.load(sys.stdin)[\"content\"])')\"", s.Placement.ImageStorage)
	w("case \",$content,\" in *,import,*) ;; *) pvesm set %s --content \"$content,import\" ;; esac", s.Placement.ImageStorage)
	w("")
	w("# 3. One role per path, with only the privileges that path needs. Every privilege comes from")
	w("#    Mamela's permission catalog (internal/proxmox/permissions.go); `mamela lab permissions` says why.")
	for _, g := range s.Grants() {
		w("ensure_role %s %q", g.Role, strings.Join(g.Privs, ","))
	}
	w("")
	w("# 4. The operating user and its privilege-separated token (no password, no login).")
	w("ensure_user %s \"Mamela lab automation\"", user)
	w("new_token %s %s %q \"Mamela lab: changes inside pool %s only\"", user, labToken, s.Proxmox.TokenSecretFile, s.Boundary.Pool)
	w("")
	w("# 5. ACLs. With privilege separation, the token gets the intersection of its own ACLs and its user's,")
	w("#    so both receive the same grants. Nothing is granted on /, /vms or other pools.")
	for _, g := range s.Grants() {
		w("pveum acl modify %s --users %s --roles %s", g.Path, user, g.Role)
		w("pveum acl modify %s --tokens '%s' --roles %s", g.Path, s.Proxmox.TokenID, g.Role)
	}
	w("")
	w("# 6. Remove the operating user's and token's ACL entries that are not in step 5 (left by earlier")
	w("#    versions of this script). Only these two identities are looked at.")
	var keep []string
	for _, g := range s.Grants() {
		keep = append(keep, g.Path+" "+g.Role)
	}
	w("keep=%q", strings.Join(keep, "\n"))
	w("pvesh get /access/acl --output-format json | python3 -c '%s' \"$keep\" '%s' '%s' |", staleACLs, user, s.Proxmox.TokenID)
	w("while read -r type ugid path role; do")
	w("  echo \"removing role $role on $path from $ugid (Mamela no longer needs it)\"")
	w("  if [ \"$type\" = token ]; then pveum acl delete \"$path\" --tokens \"$ugid\" --roles \"$role\"; else pveum acl delete \"$path\" --users \"$ugid\" --roles \"$role\"; fi")
	w("done")
	w("")
	w("# 7. The audit token: read-only everywhere (built-in PVEAuditor), used only by preflight/postflight")
	w("#    to check that guests outside the lab are unchanged.")
	if auditUser != user {
		w("ensure_user %s \"Mamela lab audit (read-only)\"", auditUser)
	}
	w("new_token %s %s %q \"Mamela lab: read-only audit\"", auditUser, auditToken, s.Proxmox.AuditTokenSecretFile)
	w("pveum acl modify / --users %s --roles PVEAuditor", auditUser)
	w("pveum acl modify / --tokens '%s' --roles PVEAuditor", s.Proxmox.AuditTokenID)
	w("")
	w("echo \"done. next: mamela lab preflight --site <site file>\"")
	return b.String()
}

// staleACLs prints "type ugid path role" for every ACL entry of the given user or token (argv 2, 3)
// whose (path, role) is not one of the lines in argv 1.
const staleACLs = `import json,sys
keep=set(tuple(l.split(" ",1)) for l in sys.argv[1].split("\\n") if l)
for a in json.load(sys.stdin):
    if a["ugid"] in (sys.argv[2], sys.argv[3]) and (a["path"], a["roleid"]) not in keep:
        print(a["type"], a["ugid"], a["path"], a["roleid"])`

// allowedPrivs maps each path the operating token may have privileges on to the allowed set.
// Pool grants propagate to the pool's guests (/vms/<id>), which must lie in the VMID range.
func (s *Site) allowedPrivs(path string) ([]string, bool) {
	for _, g := range s.Grants() {
		if g.Path == path {
			return g.Privs, true
		}
	}
	var vmid int
	if n, err := fmt.Sscanf(path, "/vms/%d", &vmid); err == nil && n == 1 && path == fmt.Sprintf("/vms/%d", vmid) &&
		vmid >= s.Boundary.VMIDMin && vmid <= s.Boundary.VMIDMax {
		return s.Grants()[0].Privs, true // the pool's grant, which reaches its VMs
	}
	return nil, false
}

// ExcessPermissions lists the (path, privilege) pairs in perms that the operating token must not
// have. perms is the result of GET /access/permissions for that token.
// MissingPermissions lists the granted privileges the token does not have (the bootstrap has not
// been run since the grants changed).
func (s *Site) MissingPermissions(perms map[string]map[string]int) []string {
	var missing []string
	for _, g := range s.Grants() {
		for _, priv := range g.Privs {
			if perms[g.Path][priv] == 0 {
				missing = append(missing, fmt.Sprintf("%s %s (for %s)", g.Path, priv, g.Reasons[priv][0]))
			}
		}
	}
	return missing
}

func (s *Site) ExcessPermissions(perms map[string]map[string]int) []string {
	var excess []string
	for _, path := range slices.Sorted(maps.Keys(perms)) {
		allowed, ok := s.allowedPrivs(path)
		for _, priv := range slices.Sorted(maps.Keys(perms[path])) {
			if perms[path][priv] == 0 {
				continue
			}
			if !ok || !slices.Contains(allowed, priv) {
				excess = append(excess, path+" "+priv)
			}
		}
	}
	return excess
}
